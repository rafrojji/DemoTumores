function $(id) { return document.getElementById(id); }
function pct(v, d=1) { return (v * 100).toFixed(d) + "%"; }
function num(v, d=4) { return Number(v).toLocaleString("es-CR", { maximumFractionDigits: d }); }

function saveCase(data) {
  const current = JSON.parse(sessionStorage.getItem("neuro_case") || "{}");
  sessionStorage.setItem("neuro_case", JSON.stringify({...current, ...data}));
}

function loadCase() {
  return JSON.parse(sessionStorage.getItem("neuro_case") || "{}");
}

function requireCase() {
  const c = loadCase();
  if (!c.caseId && !location.pathname.endsWith("index.html") && !location.pathname.endsWith("/")) {
    location.href = "index.html";
  }
  return c;
}

function zoneFromProbability(prob) {
  if (prob >= MODEL.metrics.threshold_high) {
    return {
      key: "alta",
      title: "Zona alta",
      label: "Clasificación positiva del modelo",
      cls: "danger",
      action: "Revisión prioritaria por especialista",
      clinical: "El médico debe valorar confirmación clínica y estudios complementarios."
    };
  }
  if (prob >= MODEL.metrics.threshold_alert) {
    return {
      key: "duda",
      title: "Zona de duda",
      label: "Clasificación indeterminada",
      cls: "warn",
      action: "Segunda revisión médica",
      clinical: "El médico debe integrar la imagen, expediente y posibles estudios adicionales."
    };
  }
  return {
    key: "negativa",
    title: "Zona negativa",
    label: "Clasificación negativa del modelo",
    cls: "safe",
    action: "Revisión normal",
    clinical: "El médico puede confirmar ausencia de señales relevantes o mantener seguimiento."
  };
}

function sigmoid(z) {
  return 1 / (1 + Math.exp(-z));
}

function predictFromFeatures(features) {
  let z = MODEL.intercept;
  const contributions = [];

  MODEL.features.forEach(name => {
    let raw = Number(features[name]);
    if (Number.isNaN(raw)) raw = MODEL.medians[name];

    const scaled = (raw - MODEL.means[name]) / MODEL.scales[name];
    const contribution = MODEL.coef[name] * scaled;
    z += contribution;

    contributions.push({
      name,
      raw,
      contribution,
      direction: contribution >= 0 ? "Aumenta probabilidad" : "Reduce probabilidad"
    });
  });

  contributions.sort((a,b) => Math.abs(b.contribution) - Math.abs(a.contribution));
  const probability = sigmoid(z);
  return {probability, contributions, zone: zoneFromProbability(probability)};
}

function clamp(v, min, max) { return Math.max(min, Math.min(max, v)); }

function mapToRange(value01, featureName, loKey="q05", hiKey="q95") {
  const s = MODEL.featureStats[featureName];
  const lo = s?.[loKey] ?? MODEL.medians[featureName];
  const hi = s?.[hiKey] ?? MODEL.medians[featureName];
  return lo + clamp(value01, 0, 1) * (hi - lo);
}

function computeImageFeaturesFromCanvas(canvas) {
  const ctx = canvas.getContext("2d", { willReadFrequently: true });
  const w = canvas.width, h = canvas.height;
  const img = ctx.getImageData(0, 0, w, h).data;

  const gray = new Float64Array(w*h);
  const hist = new Array(256).fill(0);
  let sum = 0;

  for (let i=0, p=0; i<img.length; i+=4, p++) {
    const g = Math.round(0.299*img[i] + 0.587*img[i+1] + 0.114*img[i+2]);
    gray[p] = g;
    hist[g]++;
    sum += g;
  }

  const n = gray.length;
  const mean = sum / n;
  let varSum = 0, skewSum = 0, kurtSum = 0;
  for (let i=0; i<n; i++) {
    const d = gray[i] - mean;
    varSum += d*d;
  }
  const variance = varSum / n;
  const std = Math.sqrt(variance) || 1;

  for (let i=0; i<n; i++) {
    const z = (gray[i] - mean) / std;
    skewSum += z**3;
    kurtSum += z**4;
  }

  let entropy = 0, energyHist = 0;
  hist.forEach(count => {
    if (count > 0) {
      const p = count / n;
      entropy -= p * Math.log2(p);
      energyHist += p*p;
    }
  });

  let contrastSum = 0, disSum = 0, homoSum = 0, corrX = 0, corrY = 0, corrXX=0, corrYY=0, corrXY=0, pairs=0;
  for (let y=0; y<h; y++) {
    for (let x=0; x<w-1; x++) {
      const a = gray[y*w + x];
      const b = gray[y*w + x + 1];
      const diff = Math.abs(a-b);
      contrastSum += diff*diff;
      disSum += diff;
      homoSum += 1 / (1 + diff);
      corrX += a; corrY += b; corrXX += a*a; corrYY += b*b; corrXY += a*b;
      pairs++;
    }
  }

  const contrastRaw = contrastSum / pairs;
  const disRaw = disSum / pairs;
  const homRaw = homoSum / pairs;
  const mx = corrX / pairs, my = corrY / pairs;
  const cov = corrXY / pairs - mx*my;
  const vx = corrXX / pairs - mx*mx;
  const vy = corrYY / pairs - my*my;
  const corrRaw = cov / Math.sqrt(Math.max(vx*vy, 1e-9));

  // Medidas simuladas de calidad a partir de nitidez/ruido. No son diagnóstico.
  const mseRaw = variance / (255*255);
  const psnrRaw = 20 * Math.log10(255 / Math.sqrt(Math.max(variance, 1e-9)));
  const ssimRaw = clamp(1 - mseRaw, 0, 1);
  const dcRaw = clamp(1 - (disRaw / 255), 0, 1);

  // Mapear datos de imagen 0-255 a rangos del dataset entrenado.
  const mean01 = mean / 255;
  const var01 = clamp(variance / (128*128), 0, 1);
  const std01 = clamp(std / 128, 0, 1);
  const entropy01 = entropy / 8;
  const skew01 = clamp((Math.abs(skewSum/n)) / 3, 0, 1);
  const kurt01 = clamp(((kurtSum/n) - 1) / 12, 0, 1);
  const contrast01 = clamp(contrastRaw / (255*255), 0, 1);
  const dis01 = clamp(disRaw / 255, 0, 1);
  const energy01 = clamp(energyHist * 20, 0, 1);
  const homo01 = clamp(homRaw * 16, 0, 1);
  const corr01 = clamp((corrRaw + 1) / 2, 0, 1);

  return {
    media: mapToRange(mean01, "media"),
    varianza: mapToRange(var01, "varianza"),
    "desviacion.estandar": mapToRange(std01, "desviacion.estandar"),
    entropia: mapToRange(entropy01, "entropia"),
    asimetria: mapToRange(skew01, "asimetria"),
    kurtosis: mapToRange(kurt01, "kurtosis"),
    contraste: mapToRange(contrast01, "contraste"),
    energia: mapToRange(energy01, "energia"),
    asm: mapToRange(energy01, "asm"),
    homogeneidad: mapToRange(homo01, "homogeneidad"),
    disiminitud: mapToRange(dis01, "disiminitud"),
    correlacion: clamp(corrRaw, -1, 1),
    psnr: mapToRange(clamp(psnrRaw / 50, 0, 1), "psnr"),
    ssim: mapToRange(ssimRaw, "ssim"),
    mse: mapToRange(mseRaw, "mse"),
    dc: mapToRange(dcRaw, "dc"),
    __raw: {
      mean, variance, std, entropy,
      skewness: skewSum/n,
      kurtosis: kurtSum/n,
      contrastRaw, dissimilarityRaw: disRaw,
      homogeneityRaw: homRaw,
      correlationRaw: corrRaw,
      psnrRaw, ssimRaw, mseRaw, dcRaw
    }
  };
}

function createSyntheticImage(type, canvas) {
  const ctx = canvas.getContext("2d");
  const w = canvas.width = 520;
  const h = canvas.height = 420;
  ctx.fillStyle = "#050814";
  ctx.fillRect(0,0,w,h);

  const cx = w/2, cy = h/2;
  const grd = ctx.createRadialGradient(cx, cy, 10, cx, cy, 190);
  grd.addColorStop(0, "#cbd5e1");
  grd.addColorStop(.45, "#64748b");
  grd.addColorStop(1, "#111827");

  ctx.save();
  ctx.translate(cx, cy);
  ctx.scale(1.08, 1.22);
  ctx.beginPath();
  ctx.arc(0,0,145,0,Math.PI*2);
  ctx.fillStyle = grd;
  ctx.fill();
  ctx.restore();

  ctx.strokeStyle = "rgba(255,255,255,.20)";
  ctx.lineWidth = 2;
  for (let i=0; i<9; i++) {
    ctx.beginPath();
    ctx.ellipse(cx, cy, 34+i*12, 22+i*15, i*.18, 0, Math.PI*2);
    ctx.stroke();
  }

  if (type === "alta") {
    const tumor = ctx.createRadialGradient(cx+56, cy-26, 5, cx+56, cy-26, 58);
    tumor.addColorStop(0, "#fecdd3");
    tumor.addColorStop(.42, "#fb7185");
    tumor.addColorStop(1, "rgba(251,113,133,0)");
    ctx.fillStyle = tumor;
    ctx.beginPath();
    ctx.arc(cx+56, cy-26, 62, 0, Math.PI*2);
    ctx.fill();
  }

  if (type === "duda") {
    const spot = ctx.createRadialGradient(cx+28, cy+18, 5, cx+28, cy+18, 44);
    spot.addColorStop(0, "#fde68a");
    spot.addColorStop(.42, "#f59e0b");
    spot.addColorStop(1, "rgba(245,158,11,0)");
    ctx.fillStyle = spot;
    ctx.beginPath();
    ctx.arc(cx+28, cy+18, 44, 0, Math.PI*2);
    ctx.fill();
  }

  // Ruido determinístico visual
  const imgData = ctx.getImageData(0, 0, w, h);
  for (let i=0; i<imgData.data.length; i+=4) {
    const noise = ((i * 17) % 19) - 9;
    imgData.data[i] = clamp(imgData.data[i] + noise, 0, 255);
    imgData.data[i+1] = clamp(imgData.data[i+1] + noise, 0, 255);
    imgData.data[i+2] = clamp(imgData.data[i+2] + noise, 0, 255);
  }
  ctx.putImageData(imgData, 0, 0);
  return canvas.toDataURL("image/png");
}

function renderFeatureTable(features, targetId="featureTable") {
  const box = $(targetId);
  if (!box) return;
  const rows = MODEL.features.map(name => `
    <tr>
      <td>${name}</td>
      <td>${num(features[name], 6)}</td>
    </tr>
  `).join("");
  box.innerHTML = `<table class="table"><tr><th>Variable extraída</th><th>Valor para el modelo</th></tr>${rows}</table>`;
}

function renderContributions(contributions, targetId="contribBox") {
  const box = $(targetId);
  if (!box) return;
  box.innerHTML = contributions.slice(0,6).map(c => {
    const w = Math.min(100, Math.abs(c.contribution) * 18);
    return `
      <div class="contrib">
        <div class="row"><strong>${c.name}</strong><span>${c.direction}</span></div>
        <div class="bar"><i style="width:${w}%"></i></div>
        <small>Aporte estandarizado: ${c.contribution.toFixed(4)}</small>
      </div>
    `;
  }).join("");
}

